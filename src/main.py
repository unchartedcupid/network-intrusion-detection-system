def run_nids(packet_limit=500):
    """Main function that starts the NIDS"""
    global rule_engine, start_time, packet_count, alert_count, all_alerts

    # Initialize
    rule_engine = RuleEngine()
    start_time = datetime.datetime.now()
    packet_count = 0
    alert_count = 0
    all_alerts = []

    # Get interface
    interface = get_default_interface()

    # Show startup screen
    show_startup_screen(interface)

    print(f"[*] Monitoring started on {interface}")
    print(f"[*] Capturing {packet_limit} packets\n")

    try:
        # Start sniffing with our callback
        packets = start_sniffing(
            interface=interface,
            packet_limit=packet_limit,
            callback=on_packet_received
        )

        # Generate summary and report
        summary = get_packet_summary(packets) if packets else {"total": packet_count}
        summary["total"] = packet_count

        # Print final summary
        print_alert_summary(all_alerts)

        # Generate HTML report
        report_path = generate_html_report(all_alerts, summary)

        # Save alerts to JSON
        json_path = os.path.join(
            os.path.dirname(__file__), "..", "logs", "session.json"
        )
        with open(json_path, "w") as f:
            json.dump({
                "session_date": start_time.strftime("%Y-%m-%d %H:%M:%S"),
                "packets_analyzed": packet_count,
                "alerts": all_alerts
            }, f, indent=2)

        print(f"[+] Session log: {json_path}")
        print(f"\n\033[92m[✔] NIDS session complete!\033[0m")
        print(f"[✔] Open report: firefox {report_path}")

    except KeyboardInterrupt:
        print("\n[!] NIDS stopped by user")

if __name__ == "__main__":
    run_nids(packet_limit=500)
