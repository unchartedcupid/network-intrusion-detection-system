# Global state
packet_count = 0
alert_count = 0
start_time = None
rule_engine = None
all_alerts = []

def on_packet_received(packet_info, raw_packet):
    """
    Called for every captured packet
    Runs all detection rules and handles any alerts
    """
    global packet_count, alert_count, all_alerts

    packet_count += 1

    # Run all detection rules on this packet
    triggered = rule_engine.analyze_packet(packet_info)

    # Handle any triggered alerts
    for alert in triggered:
        alert_count += 1
        process_alert(alert)
        all_alerts.append(alert)

    # Update dashboard every 50 packets
    if packet_count % 50 == 0:
        print_live_stats(
            packet_count,
            alert_count,
            start_time,
            all_alerts
        )

